// Vercel sets these at build and run time. The production deployment uses
// the project's production domain; previews use their own URL so their share
// images and links resolve to themselves.
export const IS_PRODUCTION = process.env.VERCEL_ENV === "production";

export const SITE_URL =
  IS_PRODUCTION && process.env.VERCEL_PROJECT_PRODUCTION_URL
    ? `https://${process.env.VERCEL_PROJECT_PRODUCTION_URL}`
    : process.env.VERCEL_URL
      ? `https://${process.env.VERCEL_URL}`
      : "http://localhost:3000";

// Where a page lives in each language, for <link rel="alternate" hreflang>
// tags and the sitemap. `path` is the part after the language prefix
// ("" for the overview, "/parkings/parking-reep" for a garage).
export function languageAlternates(path: string): Record<string, string> {
  const languages: Record<string, string> = {};
  for (const locale of routing.locales) languages[locale] = `/${locale}${path}`;
  // What to offer someone whose language we don't have.
  languages["x-default"] = `/${routing.defaultLocale}${path}`;
  return languages;
}

// The share image generated by app/[locale]/opengraph-image.tsx. Pages that
// set their own Open Graph fields must list it again, because a page's
// `openGraph` replaces the layout's as a whole — image included.
export function shareImage(locale: string, alt: string) {
  return { url: `/${locale}/opengraph-image`, width: 1200, height: 630, alt };
}

